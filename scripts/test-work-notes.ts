import assert from 'node:assert/strict';
import { appendNoteMaterial, localDay, noteDraftFingerprint } from '../src/lib/work-notes';
import type { ResumeSection, WorkExperienceItem } from '../src/types/resume';
const item: WorkExperienceItem = { id: 'i', company: '甲公司', position: '实习', startDate: '', endDate: null, current: true, description: '原有职责', technologies: ['SQL'], highlights: ['原有成果'] };
const sections = [{ id: 's', type: 'work_experience', content: { items: [item, { ...item, id: 'other', company: '乙公司' }] } }] as ResumeSection[];
const patch = appendNoteMaterial(sections, 's', structuredClone(item), ['维护报表'], ['参与一次排查']);
assert.equal(patch.items[0].description, '原有职责\n维护报表');
assert.deepEqual(patch.items[0].highlights, ['原有成果', '参与一次排查']);
assert.deepEqual(patch.items[0].technologies, ['SQL']);
assert.deepEqual(patch.items[1], (sections[0].content as { items: WorkExperienceItem[] }).items[1]);
assert.equal(item.description, '原有职责');
assert.throws(() => appendNoteMaterial([{ ...sections[0], content: patch }], 's', item, [], ['过期素材']), /刚刚有修改/);
assert.throws(() => appendNoteMaterial([], 's', item, ['材料'], []), /已删除/);
assert.throws(() => appendNoteMaterial(sections, 's', item, ['  '], []), /先选/);
const repeated = appendNoteMaterial([{ ...sections[0], content: patch }], 's', patch.items[0], ['维护报表'], ['参与一次排查']);
assert.deepEqual(repeated, patch, '重新打开审阅也不会重复追加同一素材');
const reversed = [{ ...sections[0], content: { items: [...(sections[0].content as { items: WorkExperienceItem[] }).items].reverse() } }];
assert.equal(appendNoteMaterial(reversed, 's', item, ['补充'], []).items[1].id, item.id);
assert.equal(localDay(new Date(2026, 10, 2, 23, 59)), '2026-11-02');
assert.notEqual(noteDraftFingerprint({id:'a',revision:0}), noteDraftFingerprint({id:'a',revision:1}));
console.log('PASS 工作随记：稳定定位、原内容保留、过期拒绝、去重与本地日期');
