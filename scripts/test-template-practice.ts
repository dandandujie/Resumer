import assert from 'node:assert/strict';
import {captureTemplate,arrangeTemplateSections} from '../src/lib/resume-template';
import {resolveTheme, buildThemeCss} from '../src/lib/theme-config';
import {practiceTargets,practiceRewrite,targetKey} from '../src/lib/interview-practice';
import type {Resume,ResumeSection} from '../src/types/resume';
import type {PracticeSession} from '../src/types/practice';
const section = (id:string,type:string,content:unknown):ResumeSection=>({id,resumeId:'r',type,title:id,sortOrder:0,visible:true,content,createdAt:new Date(),updatedAt:new Date()} as ResumeSection);
const sections=[section('personal','personal_info',{fullName:'不能带入模板的私人姓名',avatar:'private-photo'}),section('a','custom',{items:[{id:'i',title:'经历',description:'参与测试',highlights:['具体成果'] }]}),section('b','custom',{items:[]}),section('skills','skills',{categories:[]})];
const resume={id:'r',title:'简历',template:'modern',themeConfig:resolveTheme({sidebarWidth:42,sidebarColor:'#123456',sidebarTypes:['custom']}),sections} as Resume;
const captured=captureTemplate(resume);
assert.equal(JSON.stringify(captured).includes('不能带入模板'),false);
assert.equal(JSON.stringify(captured).includes('参与测试'),false);
assert.equal(JSON.stringify(captured).includes('private-photo'),false);
assert.equal(captured.theme.sidebarWidth,42);
const arranged=arrangeTemplateSections([sections[3],sections[2],sections[0],sections[1]],captured.sections);
assert.deepEqual(arranged.map(s=>s.id),['personal','b','a','skills']);
assert.equal(arranged.find(s=>s.id==='a')?.content,sections[1].content,'保留内容对象与条目ID');
assert.equal(resolveTheme({sidebarWidth:Infinity}).sidebarWidth,35);
assert.equal(resolveTheme({sidebarWidth:90}).sidebarWidth,45);
assert.equal(resolveTheme({sidebarColor:'red; } body {display:none}'}).sidebarColor,'#1e293b');
assert.equal(resolveTheme({lineSpacing:NaN}).lineSpacing,1.35);
assert.equal(resolveTheme({sidebarColor:'#ffffff'}).sidebarTextColor,'#1a1a1a');
assert.equal(resolveTheme({sidebarColor:'#000000'}).sidebarTextColor,'#ffffff');
assert.equal(resolveTheme({accentColor:'#f4e8da'}).headingTextColor,'#1a1a1a');
assert.ok(buildThemeCss('.paper',resolveTheme({headingStyle:'filled'})).includes('[data-section-heading]'));

assert.ok(buildThemeCss('.paper',resolveTheme({photoPosition:'hidden'})).includes('display:none'));
const targets=practiceTargets(sections);
assert.equal(targets.length,2);
assert.equal(targets[1].field,'highlights.0');
assert.notEqual(targetKey(targets[0]),targetKey(targets[1]));
const session={resumeId:'r',target:targets[0],summary:{rewriteSuggestion:'参与测试并记录结果'}} as PracticeSession;
const patch=practiceRewrite(resume,session);
assert.equal((patch.content as {items:{description:string}[]}).items[0].description,'参与测试并记录结果');
assert.equal((sections[1].content as {items:{description:string}[]}).items[0].description,'参与测试','只产生草稿补丁，不原地修改');
const edited=structuredClone(resume);(edited.sections[1].content as {items:{description:string}[]}).items[0].description='练习后新编辑';
assert.throws(()=>practiceRewrite(edited,session),/已修改/);
assert.throws(()=>practiceRewrite({...resume,id:'other'},session),/没有可采纳/);
const moved=structuredClone(resume);moved.sections.reverse();
assert.equal(practiceRewrite(moved,session).sectionId,'a','模块移位仍按稳定ID定位');
