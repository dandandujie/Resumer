  await waitFor("window.__TAURI_MOCK__.recordings[0].transcript.startsWith('校对')");
  await check("!JSON.parse(localStorage.getItem('resumer_recording_drafts_v1')).state.drafts[window.__TAURI_MOCK__.recordings[0].id]", '保存成功清除转写草稿');
