  await check("window.__TAURI_MOCK__.recordings.length===1 && !window.__TAURI_MOCK__.speechRequest", '导入仅保存本机原件，不自动上传转写');
  await click('text:转成文字');
  await check("document.querySelector('[role=alertdialog]').textContent.includes('发送到')", '转写前显示目标服务与费用提示');
  await click('text:取消');
  await check("!window.__TAURI_MOCK__.speechRequest", '取消不调用服务');
  await click('text:转成文字'); await click('text:开始转写');
  await waitFor("document.querySelector('textarea[aria-label=\"录音转写稿\"]').value.includes('缓存失效')");
  await check("window.__TAURI_MOCK__.speechRequest.config.model==='whisper-1'", '转写使用独立语音配置');
